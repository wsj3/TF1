/**
 * Pre-build script to ensure proper static export configuration
 * Run this before the Next.js build to ensure proper export settings
 */

const fs = require('fs');
const path = require('path');

console.log('Preparing environment for static export...');

// Force set environment variables
process.env.STATIC_EXPORT = 'true';
process.env.DOCKER_BUILD = 'true';
process.env.IS_EXPORT = 'true';
process.env.NEXT_PHASE = 'phase-production-build';

// Create .env.local with static export flags
const envContent = `STATIC_EXPORT=true
DOCKER_BUILD=true
IS_EXPORT=true
NEXT_PHASE=phase-production-build
`;

try {
  fs.writeFileSync('.env.local', envContent);
  console.log('Created .env.local with static export flags');
} catch (err) {
  console.error('Error creating .env.local:', err);
}

// Create static export marker file
try {
  fs.writeFileSync('.static-export-marker', 'true');
  console.log('Created .static-export-marker file');
} catch (err) {
  console.error('Error creating static export marker:', err);
}

// Create a comprehensive static export utility file
const utilsDir = path.join(process.cwd(), 'utils');
const staticExportUtil = `/**
 * Static Export Utilities
 * 
 * This file is auto-generated by next-static-export.js
 * It provides utilities for detecting and handling static export environments.
 * DO NOT EDIT MANUALLY
 */

// Constants for static export detection
export const IS_STATIC_EXPORT = true;
export const STATIC_EXPORT_MARKER = '.static-export-marker';

/**
 * Safely determine if we're in a development environment
 * This helps distinguish between development and static export builds
 */
function isDevelopmentEnvironment() {
  return (
    process.env.NODE_ENV === 'development' ||
    // Check for dev server port in browser
    (typeof window !== 'undefined' && 
     (window.location.port === '3000' || 
      window.location.port === '3001' || 
      window.location.hostname.includes('localhost')))
  );
}

/**
 * Check if the current execution context is a static export
 * Uses multiple signals to detect static export environment
 * BUT will explicitly return false for local development environments
 */
export function isStaticExport() {
  // Never treat development server as static export
  if (isDevelopmentEnvironment()) {
    return false;
  }

  return (
    // Various environment signals
    IS_STATIC_EXPORT === true ||
    process.env.STATIC_EXPORT === 'true' || 
    process.env.DOCKER_BUILD === 'true' ||
    process.env.IS_EXPORT === 'true' ||
    process.env.NODE_ENV === 'production' && process.env.NEXT_PHASE === 'phase-production-build' ||
    // Client-side detection
    typeof window !== 'undefined' && window.__NEXT_DATA__?.nextExport === true
  );
}

/**
 * Safe authentication check - returns true if the check should be bypassed
 * This provides a unified way to skip auth in various components
 */
export function shouldSkipAuthCheck() {
  return isStaticExport();
}

/**
 * Check if the current page is being statically rendered
 * This is useful in getStaticProps to determine if data fetching should be skipped
 */
export function isStaticRender() {
  return isStaticExport();
}

/**
 * A mock user object that can be used during static export
 * This ensures components don't crash when they need a user object
 */
export const mockUser = {
  id: 'static-user',
  email: 'static@example.com',
  name: 'Static User',
  role: 'user',
  isAdmin: false
};

/**
 * For use with getStaticProps to exclude pages from static generation
 * Use this in protected pages that shouldn't be pre-rendered
 */
export async function getStaticPropsWithNoGeneration() {
  return {
    notFound: true // This prevents the page from being pre-rendered
  };
}
`;

try {
  if (!fs.existsSync(utilsDir)) {
    fs.mkdirSync(utilsDir, { recursive: true });
  }
  fs.writeFileSync(path.join(utilsDir, 'static-export.js'), staticExportUtil);
  console.log('Created enhanced static export utility file');
} catch (err) {
  console.error('Error creating static export utility:', err);
}

// Update the global static-export-detection.js module at the root for easy imports
const globalDetectionModule = `/**
 * Global Static Export Detection
 * 
 * This helper file is used to quickly determine if we're in a static export environment
 * Import this at the top of your components or pages for early detection
 */

// Detect development environment
const isDevelopment = typeof process !== 'undefined' && process.env.NODE_ENV === 'development';

// Only mark as static export in non-development environments
export const IS_STATIC_EXPORT = !isDevelopment;

// Safe isStaticExport function that checks for development
export const isStaticExport = () => {
  if (isDevelopment) return false;
  return true;
};
`;

try {
  fs.writeFileSync('static-export-detection.js', globalDetectionModule);
  console.log('Created global static export detection module');
} catch (err) {
  console.error('Error creating global detection module:', err);
}

console.log('Static export environment preparation complete!'); 