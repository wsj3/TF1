/**
 * Pre-build script to ensure proper static export configuration
 * Run this before the Next.js build to ensure proper export settings
 */

const fs = require('fs');
const path = require('path');

console.log('Preparing environment for static export...');

// Force set environment variables
process.env.STATIC_EXPORT = 'true';
process.env.DOCKER_BUILD = 'true';
process.env.IS_EXPORT = 'true';
process.env.NEXT_PHASE = 'phase-production-build';

// Create .env.local with static export flags
const envContent = `STATIC_EXPORT=true
DOCKER_BUILD=true
IS_EXPORT=true
NEXT_PHASE=phase-production-build
`;

try {
  fs.writeFileSync('.env.local', envContent);
  console.log('Created .env.local with static export flags');
} catch (err) {
  console.error('Error creating .env.local:', err);
}

// Create static export marker file
try {
  fs.writeFileSync('.static-export-marker', 'true');
  console.log('Created .static-export-marker file');
} catch (err) {
  console.error('Error creating static export marker:', err);
}

// Create static export utility file
const utilsDir = path.join(process.cwd(), 'utils');
const staticExportUtil = `/**
 * Auto-generated by next-static-export.js
 * DO NOT EDIT MANUALLY
 */

// Static export detection flags
export const IS_STATIC_EXPORT = true;

/**
 * Use this function to check if we're in a static export context
 */
export function isStaticExport() {
  return true;
}

// For use with getStaticProps to exclude pages from static generation
export async function getStaticPropsWithNoGeneration() {
  return {
    notFound: true // This prevents the page from being pre-rendered
  };
}
`;

try {
  if (!fs.existsSync(utilsDir)) {
    fs.mkdirSync(utilsDir, { recursive: true });
  }
  fs.writeFileSync(path.join(utilsDir, 'static-export.js'), staticExportUtil);
  console.log('Created static export utility file');
} catch (err) {
  console.error('Error creating static export utility:', err);
}

console.log('Static export environment preparation complete!'); 